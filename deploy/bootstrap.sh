#!/usr/bin/env bash
#
# OpenBench server bootstrap for Ubuntu 22.04 / 24.04 (x86-64 or arm64).
#
# Tested target: Oracle Cloud "Always Free" Ampere A1 (2 OCPU / 12 GB running
# 24/7), but it works on any small Ubuntu box.
#
# Usage, from the root of this repository:
#
#   sudo bash deploy/bootstrap.sh
#
# It is idempotent: re-running upgrades in place and keeps .env, the database,
# and Media/ untouched.
#
# What it does NOT do: open ports, obtain a domain, or install a TLS terminator.
# See deploy/README.md for the ingress options (Cloudflare Tunnel recommended).
#
set -euo pipefail

APP_USER="openbench"
APP_DIR="/opt/openbench"
ENV_FILE="${APP_DIR}/.env"
SERVICE="openbench"
PY="python3"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m[!] %s\033[0m\n' "$*"; }
die() { printf '\033[1;31m[x] %s\033[0m\n' "$*" >&2; exit 1; }

[[ "${EUID}" -eq 0 ]] || die "run this with sudo"
[[ -f manage.py && -d OpenSite ]] || die "run this from the repository root (manage.py not found)"

# ---------------------------------------------------------------------------
# 1. System packages
# ---------------------------------------------------------------------------
say "Installing system packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq \
    python3 python3-venv python3-pip \
    git sqlite3 curl rsync ca-certificates \
    >/dev/null

# ---------------------------------------------------------------------------
# 2. Service account
# ---------------------------------------------------------------------------
if ! id "${APP_USER}" >/dev/null 2>&1; then
    say "Creating system user ${APP_USER}"
    adduser --system --group --home "${APP_DIR}" --shell /usr/sbin/nologin "${APP_USER}"
else
    say "User ${APP_USER} already exists"
fi

# ---------------------------------------------------------------------------
# 3. Code
# ---------------------------------------------------------------------------
# Copy the checkout into place unless we are already running from there.
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ "${SRC_DIR}" != "${APP_DIR}" ]]; then
    say "Copying ${SRC_DIR} -> ${APP_DIR}"
    mkdir -p "${APP_DIR}"
    # --delete keeps the tree clean but never touches .env / db / Media,
    # which are excluded below.
    rsync -a --delete \
        --exclude '.git/' \
        --exclude '.venv/' \
        --exclude '.env' \
        --exclude 'db.sqlite3' \
        --exclude 'Media/' \
        --exclude 'Static/' \
        --exclude '__pycache__/' \
        "${SRC_DIR}/" "${APP_DIR}/"
fi

mkdir -p "${APP_DIR}/Media" "${APP_DIR}/Static"

# ---------------------------------------------------------------------------
# 4. Virtualenv + dependencies
# ---------------------------------------------------------------------------
say "Creating virtualenv and installing dependencies"
if [[ ! -x "${APP_DIR}/.venv/bin/python" ]]; then
    "${PY}" -m venv "${APP_DIR}/.venv"
fi
"${APP_DIR}/.venv/bin/pip" install --quiet --upgrade pip wheel
"${APP_DIR}/.venv/bin/pip" install --quiet -r "${APP_DIR}/requirements-prod.txt"

# ---------------------------------------------------------------------------
# 5. Environment file
# ---------------------------------------------------------------------------
if [[ ! -f "${ENV_FILE}" ]]; then
    say "Generating ${ENV_FILE}"
    SECRET="$("${APP_DIR}/.venv/bin/python" -c \
        'import secrets; print(secrets.token_urlsafe(64))')"
    cat > "${ENV_FILE}" <<EOF
# Generated by deploy/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Never commit this file.

# Signs session cookies. Rotating it logs every user out.
OPENBENCH_SECRET_KEY=${SECRET}

# Set to 0 for any publicly reachable deployment.
OPENBENCH_DEBUG=0

# Comma separated. Replace with your hostname(s) once you have one.
OPENBENCH_ALLOWED_HOSTS=*

# Comma separated, e.g. https://bench.example.com
# Required for POST forms (login, test creation) when behind HTTPS.
OPENBENCH_CSRF_ORIGINS=

# Where uploaded networks, PGNs and logs live. Move this to a bigger volume if
# you start archiving a lot of PGNs.
OPENBENCH_MEDIA_ROOT=${APP_DIR}/Media
EOF
    chmod 600 "${ENV_FILE}"
else
    say "Keeping existing ${ENV_FILE}"
fi

chown -R "${APP_USER}:${APP_USER}" "${APP_DIR}"
chmod 600 "${ENV_FILE}"

# ---------------------------------------------------------------------------
# 6. Database + static assets
# ---------------------------------------------------------------------------
say "Applying migrations"
set -a; source "${ENV_FILE}"; set +a
# Django steps must run INSIDE ${APP_DIR}: manage.py resolves sqlite paths
# relative to the CWD, and a bootstrap from a separate source checkout would
# otherwise try to create db.sqlite3 in the (read-only) checkout.
cd "${APP_DIR}"
sudo -u "${APP_USER}" env $(grep -v '^#' "${ENV_FILE}" | xargs) \
    "${APP_DIR}/.venv/bin/python" manage.py migrate --noinput

say "Collecting static files"
sudo -u "${APP_USER}" env $(grep -v '^#' "${ENV_FILE}" | xargs) \
    "${APP_DIR}/.venv/bin/python" manage.py collectstatic --noinput

# ---------------------------------------------------------------------------
# 7. Admin user
# ---------------------------------------------------------------------------
# TRAP: `manage.py createsuperuser` is NOT enough. OpenBench authenticates
# workers with authenticate(request, requireEnabled=True) (OpenBench/views.py:121),
# which does Profile.objects.get(user=user) and checks .enabled. A user created
# by createsuperuser has no Profile row, so every worker attach fails with
# "Bad Credentials" and nothing else in the logs explains why.
#
# Scripts/create_user.py is the correct path: it creates the User AND the Profile.
if ! sudo -u "${APP_USER}" env $(grep -v '^#' "${ENV_FILE}" | xargs) \
        "${APP_DIR}/.venv/bin/python" - <<'PY'
import os, django, sys
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'OpenSite.settings')
django.setup()
from OpenBench.models import Profile
sys.exit(0 if Profile.objects.filter(enabled=True).exists() else 1)
PY
then
    if [[ -n "${OPENBENCH_ADMIN_USER:-}" && -n "${OPENBENCH_ADMIN_PASSWORD:-}" ]]; then
        say "Creating admin ${OPENBENCH_ADMIN_USER} (with enabled Profile)"
        sudo -u "${APP_USER}" env $(grep -v '^#' "${ENV_FILE}" | xargs) \
            "${APP_DIR}/.venv/bin/python" "${APP_DIR}/Scripts/create_user.py" \
                --username "${OPENBENCH_ADMIN_USER}" \
                --email "${OPENBENCH_ADMIN_EMAIL:-admin@localhost}" \
                --password "${OPENBENCH_ADMIN_PASSWORD}" \
                --enabled --approver --superuser
    else
        warn "No enabled user yet. Workers cannot attach until one exists."
        warn "Run (NOT createsuperuser):"
        warn "  sudo -u ${APP_USER} ${APP_DIR}/.venv/bin/python ${APP_DIR}/Scripts/create_user.py \\"
        warn "      --username you --email you@example.com --enabled --approver --superuser"
        warn "Or re-run as: OPENBENCH_ADMIN_USER=you OPENBENCH_ADMIN_PASSWORD=... sudo -E bash deploy/bootstrap.sh"
    fi
fi

# ---------------------------------------------------------------------------
# 8. systemd
# ---------------------------------------------------------------------------
say "Installing systemd unit"
install -m 644 "${APP_DIR}/deploy/openbench.service" "/etc/systemd/system/${SERVICE}.service"
systemctl daemon-reload
systemctl enable "${SERVICE}" >/dev/null
systemctl restart "${SERVICE}"

sleep 2
if systemctl is-active --quiet "${SERVICE}"; then
    say "OpenBench is running on 127.0.0.1:8000"
else
    warn "Service failed to start. Recent logs:"
    journalctl -u "${SERVICE}" -n 40 --no-pager || true
    exit 1
fi

# ---------------------------------------------------------------------------
# 9. Health check
# ---------------------------------------------------------------------------
say "Health check"
if curl -fsS -o /dev/null -H 'Host: localhost' http://127.0.0.1:8000/; then
    echo "    HTTP OK"
else
    warn "HTTP check failed; inspect: journalctl -u ${SERVICE} -n 50"
fi

cat <<EOF

────────────────────────────────────────────────────────────────────────
Server is up. Next:

  1. Expose it (see deploy/README.md):
       - Cloudflare Tunnel  (recommended, no open ports, free TLS)
       - or open port 80/443 and put Caddy in front

  2. Set the hostname in ${ENV_FILE}:
       OPENBENCH_ALLOWED_HOSTS=bench.example.com
       OPENBENCH_CSRF_ORIGINS=https://bench.example.com
     then: systemctl restart ${SERVICE}

  3. Log in at /admin/ and register:
       - Engine        (source zip URL, e.g. https://github.com/you/Luminex/archive/<sha>.zip)
       - EngineConfig  (build path, compilers, cpuflags, systems)
       - Book
       - Network       (upload the .nnue)

  4. Attach workers (worker.py has no --server flag; client.py is the entry
     point and forwards -T/-N to worker.py):
       python3 Client/client.py -U <user> -P <pass> -S http://<host> -T <games> -N 1

  Logs:    journalctl -u ${SERVICE} -f
  Restart: systemctl restart ${SERVICE}
────────────────────────────────────────────────────────────────────────
EOF
